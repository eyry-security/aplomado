"""Authenticated-scanning glue for Aplomado bug-hunting scans.

The highest-payout surface sits behind login. This module provides:

- :class:`CookieJar` — the run's session store. It understands the canonical
  Netscape cookie jar at ``scratch/cookies.txt`` (the same file curl's ``-c``
  writes), so the shell's curl session and the browser tools share one
  authenticated session. Operators can also paste browser-exported cookies
  (or a bearer token) once; every bughunter tool built with the same jar
  injects them via ``-H "Cookie: …"`` / header flags. Two jars with two
  accounts enable IDOR differential testing.
- :func:`auth_tools` — the agent-facing tools: ``set_auth_session``
  stores credentials, ``show_auth_status`` reports what's configured
  (never echoes secret values back).

Secrets are never logged: status reports show presence, not content.
"""

from __future__ import annotations

from urllib.parse import urlsplit

from langchain_core.tools import BaseTool, StructuredTool

COOKIE_JAR_PATH = "scratch/cookies.txt"
NETSCAPE_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# Generated by Aplomado — the canonical authenticated-session jar.\n"
)


def _cookie_record(
    name: str,
    value: str,
    *,
    domain: str = "",
    path: str = "/",
    secure: bool = False,
    http_only: bool = False,
    expires: int = 0,
) -> dict:
    return {
        "name": name,
        "value": value,
        "domain": domain,
        "path": path or "/",
        "secure": bool(secure),
        "http_only": bool(http_only),
        "expires": int(expires or 0),
    }


def parse_cookie_jar(text: str) -> list[dict]:
    """Parse Netscape/Mozilla or plain ``Cookie:`` text into records."""
    records: list[dict] = []
    if not text:
        return records
    lines = text.splitlines()
    netscape = any(
        ("\t" in line and not line.lstrip().startswith("#")) for line in lines
    ) or any(line.startswith("# Netscape HTTP Cookie File") for line in lines)
    if netscape:
        for raw in lines:
            line = raw.strip("\r\n")
            if not line or (line.startswith("#") and not line.startswith("#HttpOnly_")):
                continue
            http_only = line.startswith("#HttpOnly_")
            if http_only:
                line = line[len("#HttpOnly_"):]
            parts = line.split("\t")
            if len(parts) < 7:
                continue
            domain, _include_subdomains, path, secure, expires, name = parts[:6]
            value = "\t".join(parts[6:])
            try:
                expiry = int(float(expires or 0))
            except (TypeError, ValueError):
                expiry = 0
            records.append(
                _cookie_record(
                    name,
                    value,
                    domain=domain,
                    path=path or "/",
                    secure=str(secure).strip().upper() == "TRUE",
                    http_only=http_only,
                    expires=expiry,
                )
            )
        return records

    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.lower().startswith("cookie:"):
            line = line.split(":", 1)[1].strip()
        for pair in line.split(";"):
            name, sep, value = pair.strip().partition("=")
            if sep and name:
                records.append(_cookie_record(name.strip(), value.strip()))
    return records


def format_cookie_jar(records: list[dict]) -> str:
    """Render records as a Netscape/Mozilla cookie jar file."""
    output = [NETSCAPE_HEADER.rstrip("\n")]
    for record in records:
        name = str(record.get("name") or "").strip()
        value = str(record.get("value") or "")
        if not name:
            continue
        domain = str(record.get("domain") or "").strip()
        if not domain:
            continue
        include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
        path = str(record.get("path") or "/")
        secure = "TRUE" if record.get("secure") else "FALSE"
        try:
            expires = int(record.get("expires") or 0)
        except (TypeError, ValueError):
            expires = 0
        prefix = "#HttpOnly_" if record.get("http_only") else ""
        output.append(
            f"{prefix}{domain}\t{include_subdomains}\t{path}\t{secure}\t"
            f"{expires}\t{name}\t{value}"
        )
    return "\n".join(output) + "\n"


def cookie_header_from_records(records: list[dict]) -> str:
    """Return the ``Cookie: …`` header for *records* (or ``""``)."""
    pairs = [
        f"{record['name']}={record['value']}"
        for record in records
        if record.get("name")
    ]
    return f"Cookie: {'; '.join(pairs)}" if pairs else ""


def _target_host(url: str) -> str:
    try:
        return (urlsplit(url).hostname or "").strip().lower()
    except ValueError:
        return ""


class CookieJar:
    """Session credentials shared across bughunter and browser tools.

    With a sandbox, the jar is backed by ``scratch/cookies.txt`` — the same
    canonical jar curl writes with ``-c`` and reads with ``-b``. A missing
    file simply means "no stored cookies yet".
    """

    def __init__(self, sandbox=None, path: str = COOKIE_JAR_PATH) -> None:
        self.sandbox = sandbox
        self.path = path
        self._cookies: str = ""
        self._auth_header: str = ""
        self._records: list[dict] = []

    # -- jar persistence -------------------------------------------------
    def _read_jar(self) -> str:
        if self.sandbox is None:
            return ""
        try:
            return self.sandbox.read_file(self.path)
        except Exception:  # noqa: BLE001 - a missing jar is normal
            return ""

    def _write_jar(self, text: str) -> None:
        if self.sandbox is None:
            return
        try:
            self.sandbox.write_file(self.path, text)
        except Exception:  # noqa: BLE001 - credential storage is best-effort
            pass

    def refresh(self) -> list[dict]:
        """Reload records from the canonical jar if it exists."""
        text = self._read_jar()
        if text.strip():
            records = parse_cookie_jar(text)
            if records:
                self._records = records
                self._cookies = cookie_header_from_records(records).removeprefix(
                    "Cookie: "
                )
        return self._records

    def save_browser_cookies(self, cookies: list[dict]) -> None:
        """Write browser cookies back to the canonical jar."""
        records: list[dict] = []
        for cookie in cookies:
            if not isinstance(cookie, dict) or not cookie.get("name"):
                continue
            records.append(
                _cookie_record(
                    str(cookie["name"]),
                    str(cookie.get("value") or ""),
                    domain=str(cookie.get("domain") or ""),
                    path=str(cookie.get("path") or "/"),
                    secure=bool(cookie.get("secure")),
                    http_only=bool(
                        cookie.get("http_only", cookie.get("httpOnly", False))
                    ),
                    expires=cookie.get("expires") or 0,
                )
            )
        if not records:
            return
        self._records = records
        self._cookies = cookie_header_from_records(records).removeprefix("Cookie: ")
        self._write_jar(format_cookie_jar(records))

    def browser_cookies(self, url: str) -> list[dict]:
        """Return jar records targeted at *url*'s host for the browser."""
        records = self.refresh()
        if not records and self._cookies:
            records = parse_cookie_jar(self._cookies)
        host = _target_host(url)
        targeted: list[dict] = []
        for record in records:
            item = dict(record)
            domain = str(item.get("domain") or "").strip().lower().lstrip(".")
            if domain and host and host != domain and not host.endswith("." + domain):
                continue
            if not item.get("domain"):
                item["domain"] = host
            item["url"] = url
            targeted.append(item)
        return targeted

    # -- credential store ------------------------------------------------
    def set_cookies(self, cookies: str) -> None:
        """Store a browser-exported cookie string (``a=b; c=d``)."""
        self._cookies = cookies.strip()
        self._records = parse_cookie_jar(self._cookies)
        if self._records and any(record.get("domain") for record in self._records):
            self._write_jar(format_cookie_jar(self._records))
        elif self._cookies:
            # Keep the canonical path present for operators/tools that read it,
            # even before a domain is known (the browser fills it on first use).
            self._write_jar(self._cookies + "\n")

    def set_auth_header(self, value: str) -> None:
        """Store an Authorization header value (e.g. ``Bearer …``)."""
        value = value.strip()
        if value and not value.lower().startswith("bearer "):
            value = "Bearer " + value
        self._auth_header = value

    def cookie_header(self) -> str:
        """Return the ``Cookie: …`` header line, or ``""`` if unset."""
        if not self._cookies:
            self.refresh()
        if not self._cookies:
            return ""
        return f"Cookie: {self._cookies}"

    def extra_headers(self) -> list[str]:
        """All configured header lines (Cookie and/or Authorization)."""
        headers: list[str] = []
        header = self.cookie_header()
        if header:
            headers.append(header)
        if self._auth_header:
            headers.append(f"Authorization: {self._auth_header}")
        return headers

    def configured(self) -> bool:
        if not self._cookies:
            self.refresh()
        return bool(self._cookies or self._auth_header)

    def status(self) -> str:
        """Presence-only status — never echoes credential content."""
        cookie_state = "set" if self.cookie_header() else "not set"
        parts = [
            f"cookies: {cookie_state}",
            "authorization: set" if self._auth_header else "authorization: not set",
        ]
        return ", ".join(parts)


def auth_tools(cookie_jar: CookieJar) -> list[BaseTool]:
    """Return [set_auth_session, show_auth_status] bound to *cookie_jar*."""

    def set_auth_session(cookies: str = "", authorization: str = "") -> str:
        """Store session credentials for authenticated scanning.

        cookies: browser-exported cookie string, e.g.
        "session=abc123; csrftoken=xyz" (DevTools → Application →
        Cookies). authorization: bearer token or full "Authorization: …"
        value. Stored ONCE, then injected into every bughunter tool
        (katana, nuclei, dalfox, ffuf, curl checks). Values are never
        echoed back or logged.
        """
        if cookies.strip():
            cookie_jar.set_cookies(cookies)
        if authorization.strip():
            cookie_jar.set_auth_header(authorization)
        if not cookie_jar.configured():
            return "error: no credentials provided — pass cookies and/or authorization"
        return (
            "auth session stored. All bughunter tools will now send it. "
            f"Status: {cookie_jar.status()}."
        )

    def show_auth_status() -> str:
        """Check whether an auth session is configured (presence only)."""
        return f"auth status: {cookie_jar.status()}."

    return [
        StructuredTool.from_function(
            set_auth_session,
            name="set_auth_session",
            description=(
                "Store login session credentials ONCE for authenticated "
                "scanning: paste browser cookies and/or a bearer token. "
                "Every bughunter tool then sends them automatically. "
                "Never echoed back."
            ),
        ),
        StructuredTool.from_function(
            show_auth_status,
            name="show_auth_status",
            description=(
                "Check whether an authenticated session is configured "
                "(reports presence only, never secret values)."
            ),
        ),
    ]
